using System.Text;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.Hosting;

namespace NoneadCSS.Application.Security;

/// <summary>
/// JWT 启动期配置解析与强制校验。
/// 从 Program.cs 的启动脚本中抽离，使其可通过单元测试覆盖 Fail-Fast 分支：
///   - 生产环境强制使用环境变量（不允许回落到 appsettings.json 的占位密钥）
///   - 开发环境允许使用自动生成的随机开发密钥（每次启动随机，防止误用于生产）
///   - 密钥强度校验：按 UTF-8 字节数 >= 32（HS256 最低要求）
/// 返回标准化后的 (SecretKey, Issuer, Audience, AccessTokenExpireMinutes)，供 Program.cs 统一写回 IConfiguration，
/// 这样 AuthService / 其他模块通过 IConfiguration 读取时能获得一致的值。
/// </summary>
public static class JwtBootstrapValidator
{
    public const string JwtKeyEnvDoubleUnderscore = "JWT__Key";
    public const string JwtKeyEnvUnderscore = "JWT_KEY";
    public const string JwtIssuerEnvDoubleUnderscore = "JWT__Issuer";
    public const string JwtIssuerEnvUnderscore = "JWT_ISSUER";
    public const string JwtAudienceEnvDoubleUnderscore = "JWT__Audience";
    public const string JwtAudienceEnvUnderscore = "JWT_AUDIENCE";
    public const string JwtAccessTokenExpireMinutesEnvDoubleUnderscore = "JWT__AccessTokenExpireMinutes";
    public const string JwtAccessTokenExpireMinutesEnvUnderscore = "JWT_ACCESSTOKENEXPIREMINUTES";

    public const string DefaultIssuer = "NoneadCSS";
    public const string DefaultAudience = "NoneadCSSApi";
    public const int DefaultAccessTokenExpireMinutes = 60;

    /// <summary>
    /// HS256 最低密钥长度（UTF-8 字节数）。NIST 推荐：哈希输出 256 bit 的算法，密钥长度 >= 256 bit。
    /// </summary>
    public const int MinimumSecretKeyBytes = 32;

    /// <summary>生产环境强制要求：JWT Key 必须通过环境变量注入。</summary>
    public const string ProductionKeyMissingMessage
        = "生产环境必须设置 JWT__Key 或 JWT_KEY 环境变量。请参考 README.md 文档配置环境变量。";

    public const string DevelopmentKeyAutoGenerateInfoTag = "[DEV-AUTO]";

    /// <summary>
    /// 解析并校验 JWT 启动配置。失败会抛 <see cref="InvalidOperationException"/>，由宿主启动期 Fail-Fast。
    /// </summary>
    /// <param name="configuration">启动期 Configuration（已合并 appsettings + 环境变量 + 命令行）。</param>
    /// <param name="environment">宿主环境，用于区分 Development / Production。</param>
    /// <param name="envAccessor">
    /// 可选的环境变量读取委托；默认用 <see cref="Environment.GetEnvironmentVariable(string)"/>。
    /// 传入可伪造的委托便于单元测试，不再污染真实进程环境变量。
    /// </param>
    public static JwtBootstrapSettings ValidateAndResolve(
        IConfiguration configuration,
        IHostEnvironment environment,
        Func<string, string?>? envAccessor = null)
    {
        ArgumentNullException.ThrowIfNull(configuration);
        ArgumentNullException.ThrowIfNull(environment);
        envAccessor ??= key => Environment.GetEnvironmentVariable(key);

        string? TryCfg(params string[] keys)
        {
            foreach (var k in keys)
            {
                var v = envAccessor(k);
                if (!string.IsNullOrWhiteSpace(v)) return v;
            }
            return null;
        }

        var keyFromEnv = TryCfg(JwtKeyEnvDoubleUnderscore, JwtKeyEnvUnderscore);
        var issuer = TryCfg(JwtIssuerEnvDoubleUnderscore, JwtIssuerEnvUnderscore) ?? configuration["Jwt:Issuer"];
        var audience = TryCfg(JwtAudienceEnvDoubleUnderscore, JwtAudienceEnvUnderscore) ?? configuration["Jwt:Audience"];
        var expireRaw = TryCfg(JwtAccessTokenExpireMinutesEnvDoubleUnderscore, JwtAccessTokenExpireMinutesEnvUnderscore)
                        ?? configuration["Jwt:AccessTokenExpireMinutes"];

        // ── 生产环境：Key 必须来自环境变量，禁止回退 appsettings ─────────────
        if (environment.IsProduction())
        {
            if (string.IsNullOrEmpty(keyFromEnv))
            {
                throw new InvalidOperationException(ProductionKeyMissingMessage);
            }
        }

        string jwtKey;
        bool isAutoGeneratedDevKey = false;
        if (!string.IsNullOrEmpty(keyFromEnv))
        {
            jwtKey = keyFromEnv;
        }
        else if (!string.IsNullOrEmpty(configuration["Jwt:SecretKey"]))
        {
            jwtKey = configuration["Jwt:SecretKey"]!;
        }
        else if (environment.IsDevelopment())
        {
            var devKeyBytes = System.Security.Cryptography.RandomNumberGenerator.GetBytes(48);
            jwtKey = Convert.ToBase64String(devKeyBytes);
            isAutoGeneratedDevKey = true;
        }
        else
        {
            throw new InvalidOperationException(
                "JWT 密钥未配置。请设置 JWT__Key 环境变量。生产环境必须使用环境变量。");
        }

        // ── 密钥强度：HS256 按 UTF-8 字节数 >= 32 ──────────────────────────────
        var jwtKeyBytes = Encoding.UTF8.GetByteCount(jwtKey);
        if (jwtKeyBytes < MinimumSecretKeyBytes)
        {
            throw new InvalidOperationException(
                $"JWT 密钥强度不足：当前 {jwtKeyBytes} 字节，至少需要 {MinimumSecretKeyBytes} 字节以满足 HS256 安全要求（建议使用 48+ 字节随机密钥）。");
        }

        // ── 过期时间（可选配置，分钟数，非法值走默认 60） ───────────────────
        int accessTokenExpireMinutes;
        if (string.IsNullOrWhiteSpace(expireRaw) || !int.TryParse(expireRaw, out accessTokenExpireMinutes) || accessTokenExpireMinutes <= 0)
        {
            accessTokenExpireMinutes = DefaultAccessTokenExpireMinutes;
        }

        issuer = string.IsNullOrWhiteSpace(issuer) ? DefaultIssuer : issuer;
        audience = string.IsNullOrWhiteSpace(audience) ? DefaultAudience : audience;

        return new JwtBootstrapSettings(
            SecretKey: jwtKey,
            Issuer: issuer,
            Audience: audience,
            AccessTokenExpireMinutes: accessTokenExpireMinutes,
            IsAutoGeneratedDevelopmentKey: isAutoGeneratedDevKey);
    }
}

/// <summary>解析完成后的标准化 JWT 启动期配置。</summary>
public sealed record JwtBootstrapSettings(
    string SecretKey,
    string Issuer,
    string Audience,
    int AccessTokenExpireMinutes,
    bool IsAutoGeneratedDevelopmentKey);
