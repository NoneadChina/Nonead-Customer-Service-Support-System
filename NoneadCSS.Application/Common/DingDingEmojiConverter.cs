/// 钉钉客户端用户选择内置表情发送时，推送的 msgtype 为 "text"，text.content 为 "[表情名]" 格式，
/// 直接存储会导致会话记录显示 [流泪] 这样的原始中文名称。本转换器在消息入库前统一转换为 emoji。
