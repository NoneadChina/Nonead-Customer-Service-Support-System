    /// <summary>
    /// 匹配 [表情名] 格式的正则表达式。
    /// </summary>
    private static readonly Regex EmojiRegex = new(
        @"\[[^\[\]]{1,10}\]",
        RegexOptions.Compiled);

    /// <summary>
    /// 将文本中的钉钉表情名称 [表情名] 替换为 Unicode emoji。
    /// 支持表情名称嵌入文本中、多个表情连续出现等场景。
    /// 未匹配到任何已知表情名称时保留原文（不误伤普通方括号文本）。
    /// </summary>
    /// <param name="content">可能包含钉钉表情名称的文本</param>
    /// <returns>表情名称已替换为 emoji 的文本</returns>
    public static string Convert(string? content)
    {
        if (string.IsNullOrEmpty(content)) return content ?? string.Empty;
        return EmojiRegex.Replace(content, m =>
            EmojiMap.TryGetValue(m.Value, out var emoji) ? emoji : m.Value);
    }

