using System.Text;
using FluentAssertions;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.Hosting;
using NoneadCSS.Application.Security;

namespace NoneadCSS.Tests.Services;

public class JwtBootstrapValidatorTests
{
    private const string ValidKey40Chars = "abcdefghijklmnopqrstuvwxyz0123456789ABCD";
    private const string ValidKey32Chars = "12345678901234567890123456789012";

    private static IConfiguration BuildConfig(Dictionary<string, string?>? values = null)
    {
        values ??= new Dictionary<string, string?>();
        return new ConfigurationBuilder()
            .AddInMemoryCollection(values)
            .Build();
    }

    private static IHostEnvironment BuildEnv(string environmentName)
    {
        return new Microsoft.Extensions.Hosting.Internal.HostingEnvironment
        {
            EnvironmentName = environmentName
        };
    }

    private static Func<string, string?> BuildEnvAccessor(Dictionary<string, string?> envVars)
    {
        return key => envVars.TryGetValue(key, out var v) ? v : null;
    }

    #region 参数空值校验

    [Fact]
    public void ValidateAndResolve_NullConfiguration_Throws_ArgumentNullException()
    {
        var env = BuildEnv(Environments.Development);
        var envAccessor = BuildEnvAccessor(new Dictionary<string, string?>());

        Action act = () => JwtBootstrapValidator.ValidateAndResolve(null!, env, envAccessor);

        act.Should().Throw<ArgumentNullException>().And.ParamName.Should().Be("configuration");
    }

    [Fact]
    public void ValidateAndResolve_NullEnvironment_Throws_ArgumentNullException()
    {
        var config = BuildConfig();
        var envAccessor = BuildEnvAccessor(new Dictionary<string, string?>());

        Action act = () => JwtBootstrapValidator.ValidateAndResolve(config, null!, envAccessor);

        act.Should().Throw<ArgumentNullException>().And.ParamName.Should().Be("environment");
    }

    #endregion

    #region Production 环境

    [Fact]
    public void Production_MissingEnvKey_Throws_InvalidOperation()
    {
        var config = BuildConfig(new Dictionary<string, string?>
        {
            ["Jwt:SecretKey"] = ValidKey40Chars
        });
        var env = BuildEnv(Environments.Production);
        var envAccessor = BuildEnvAccessor(new Dictionary<string, string?>());

        Action act = () => JwtBootstrapValidator.ValidateAndResolve(config, env, envAccessor);

        act.Should().Throw<InvalidOperationException>()
            .WithMessage("*生产环境必须设置*");
    }

    [Fact]
    public void Production_WithJWT__KeyEnv_ValidLength_ShouldReturnSettings()
    {
        var config = BuildConfig();
        var env = BuildEnv(Environments.Production);
        var envAccessor = BuildEnvAccessor(new Dictionary<string, string?>
        {
            ["JWT__Key"] = ValidKey40Chars
        });

        var result = JwtBootstrapValidator.ValidateAndResolve(config, env, envAccessor);

        result.Should().NotBeNull();
        result.SecretKey.Should().Be(ValidKey40Chars);
        result.Issuer.Should().Be(JwtBootstrapValidator.DefaultIssuer);
        result.Audience.Should().Be(JwtBootstrapValidator.DefaultAudience);
        result.AccessTokenExpireMinutes.Should().Be(JwtBootstrapValidator.DefaultAccessTokenExpireMinutes);
        result.IsAutoGeneratedDevelopmentKey.Should().BeFalse();
    }

    [Fact]
    public void Production_WithJWT_KEY_Fallback_ShouldWork()
    {
        var config = BuildConfig();
        var env = BuildEnv(Environments.Production);
        var envAccessor = BuildEnvAccessor(new Dictionary<string, string?>
        {
            ["JWT__Key"] = "",
            ["JWT_KEY"] = ValidKey40Chars
        });

        var result = JwtBootstrapValidator.ValidateAndResolve(config, env, envAccessor);

        result.Should().NotBeNull();
        result.SecretKey.Should().Be(ValidKey40Chars);
        result.IsAutoGeneratedDevelopmentKey.Should().BeFalse();
    }

    [Fact]
    public void Production_ShortKey_ShouldThrow_StrengthInsufficient()
    {
        var config = BuildConfig();
        var env = BuildEnv(Environments.Production);
        var envAccessor = BuildEnvAccessor(new Dictionary<string, string?>
        {
            ["JWT__Key"] = "1234567890"
        });

        Action act = () => JwtBootstrapValidator.ValidateAndResolve(config, env, envAccessor);

        act.Should().Throw<InvalidOperationException>()
            .WithMessage("*JWT 密钥强度不足*");
    }

    [Fact]
    public void Production_PreferEnvOverAppSettings()
    {
        var config = BuildConfig(new Dictionary<string, string?>
        {
            ["Jwt:SecretKey"] = "short-wrong-key"
        });
        var env = BuildEnv(Environments.Production);
        var envAccessor = BuildEnvAccessor(new Dictionary<string, string?>
        {
            ["JWT__Key"] = ValidKey40Chars
        });

        var result = JwtBootstrapValidator.ValidateAndResolve(config, env, envAccessor);

        result.SecretKey.Should().Be(ValidKey40Chars);
    }

    [Fact]
    public void Production_ExpireMinutes_PreferEnv()
    {
        var config = BuildConfig();
        var env = BuildEnv(Environments.Production);
        var envAccessor = BuildEnvAccessor(new Dictionary<string, string?>
        {
            ["JWT__Key"] = ValidKey40Chars,
            ["JWT__AccessTokenExpireMinutes"] = "120"
        });

        var result = JwtBootstrapValidator.ValidateAndResolve(config, env, envAccessor);

        result.AccessTokenExpireMinutes.Should().Be(120);
    }

    [Fact]
    public void Production_ExpireMinutes_Invalid_Fallback_ToDefault_60()
    {
        var config = BuildConfig();
        var env = BuildEnv(Environments.Production);
        var envAccessor1 = BuildEnvAccessor(new Dictionary<string, string?>
        {
            ["JWT__Key"] = ValidKey40Chars,
            ["JWT__AccessTokenExpireMinutes"] = "abc"
        });
        var envAccessor2 = BuildEnvAccessor(new Dictionary<string, string?>
        {
            ["JWT__Key"] = ValidKey40Chars,
            ["JWT__AccessTokenExpireMinutes"] = "-5"
        });

        var result1 = JwtBootstrapValidator.ValidateAndResolve(config, env, envAccessor1);
        var result2 = JwtBootstrapValidator.ValidateAndResolve(config, env, envAccessor2);

        result1.AccessTokenExpireMinutes.Should().Be(60);
        result2.AccessTokenExpireMinutes.Should().Be(60);
    }

    [Fact]
    public void Production_CustomIssuerAudience_FromEnv()
    {
        var config = BuildConfig();
        var env = BuildEnv(Environments.Production);
        var envAccessor = BuildEnvAccessor(new Dictionary<string, string?>
        {
            ["JWT__Key"] = ValidKey40Chars,
            ["JWT__Issuer"] = "prod-iss",
            ["JWT__Audience"] = "prod-aud"
        });

        var result = JwtBootstrapValidator.ValidateAndResolve(config, env, envAccessor);

        result.Issuer.Should().Be("prod-iss");
        result.Audience.Should().Be("prod-aud");
    }

    #endregion

    #region Development 环境

    [Fact]
    public void Development_NoConfig_AutoGenerateKey_ShouldReturn_AutoGenFlag()
    {
        var config = BuildConfig();
        var env = BuildEnv(Environments.Development);
        var envAccessor = BuildEnvAccessor(new Dictionary<string, string?>());

        var result = JwtBootstrapValidator.ValidateAndResolve(config, env, envAccessor);

        result.IsAutoGeneratedDevelopmentKey.Should().BeTrue();
        result.SecretKey.Length.Should().BeGreaterOrEqualTo(64);
        Encoding.UTF8.GetByteCount(result.SecretKey).Should().BeGreaterOrEqualTo(48);
    }

    [Fact]
    public void Development_AppSettingsSecretKey_ValidLength_ShouldBeUsed()
    {
        var config = BuildConfig(new Dictionary<string, string?>
        {
            ["Jwt:SecretKey"] = ValidKey40Chars
        });
        var env = BuildEnv(Environments.Development);
        var envAccessor = BuildEnvAccessor(new Dictionary<string, string?>());

        var result = JwtBootstrapValidator.ValidateAndResolve(config, env, envAccessor);

        result.IsAutoGeneratedDevelopmentKey.Should().BeFalse();
        result.SecretKey.Should().Be(ValidKey40Chars);
        result.Issuer.Should().Be(JwtBootstrapValidator.DefaultIssuer);
        result.Audience.Should().Be(JwtBootstrapValidator.DefaultAudience);
    }

    [Fact]
    public void Development_AppSettingsShortKey_ShouldThrowStrength()
    {
        var config = BuildConfig(new Dictionary<string, string?>
        {
            ["Jwt:SecretKey"] = "123"
        });
        var env = BuildEnv(Environments.Development);
        var envAccessor = BuildEnvAccessor(new Dictionary<string, string?>());

        Action act = () => JwtBootstrapValidator.ValidateAndResolve(config, env, envAccessor);

        act.Should().Throw<InvalidOperationException>()
            .WithMessage("*JWT 密钥强度不足*");
    }

    [Fact]
    public void Development_AppSettingsIssuerAudienceExpire_ShouldBeRead()
    {
        var config = BuildConfig(new Dictionary<string, string?>
        {
            ["Jwt:SecretKey"] = ValidKey40Chars,
            ["Jwt:Issuer"] = "MyIss",
            ["Jwt:Audience"] = "MyAud",
            ["Jwt:AccessTokenExpireMinutes"] = "30"
        });
        var env = BuildEnv(Environments.Development);
        var envAccessor = BuildEnvAccessor(new Dictionary<string, string?>());

        var result = JwtBootstrapValidator.ValidateAndResolve(config, env, envAccessor);

        result.Issuer.Should().Be("MyIss");
        result.Audience.Should().Be("MyAud");
        result.AccessTokenExpireMinutes.Should().Be(30);
    }

    #endregion
}
